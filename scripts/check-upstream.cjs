/**
 * Upstream fidelity check (CI): proves vendor/upstream/ is still the pinned
 * upstream tag, so the "chat UI is the original, unmodified" claim stays true.
 *
 * It sparse-clones the pinned tag into a temp dir and diffs it against the
 * vendored tree. Only the differences documented in docs/UPSTREAM.md are
 * tolerated — anything else fails the check.
 *
 *   npm run check:upstream
 *
 * Requires network + git. Skipped (exit 0 with a notice) when either is missing,
 * so it can live in the main CI job without breaking offline builds.
 */
const { execFileSync } = require("node:child_process");
const { existsSync, mkdtempSync, rmSync } = require("node:fs");
const { tmpdir } = require("node:os");
const { join } = require("node:path");

const REPO = "https://github.com/JohnnyZ93/pi-agent-studio";
const TAG = "v1.3.8";
const SPARSE_PATHS = ["pi-chat", "bridge", "pi-mcp", "assets"];

/** Documented local differences (docs/UPSTREAM.md → "Local differences"). */
const ALLOWED = [
  "bridge/mcp/index.js", // build output tracked on purpose (app loads it)
  "pi-chat/package-lock.json", // produced by npm install inside the vendored dir
  "pi-chat/src/model-icons-data.ts", // generated by pi-chat/scripts/extract-model-icons.mjs
];

/** Paths that never take part in the comparison. */
const IGNORED_NAMES = new Set(["node_modules", "dist", ".git"]);

function git(args, cwd) {
  return execFileSync("git", args, { cwd, encoding: "utf8", stdio: ["ignore", "pipe", "pipe"] });
}

function hasGit() {
  try {
    execFileSync("git", ["--version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}

/** Relative paths present in one tree but not the other, or with other content. */
function compareTrees(a, b, rel, out) {
  const fs = require("node:fs");
  const { readdirSync, readFileSync, statSync } = fs;
  let entries;
  try {
    entries = readdirSync(join(a, rel), { withFileTypes: true });
  } catch {
    out.missing.push(rel);
    return;
  }
  for (const entry of entries) {
    if (IGNORED_NAMES.has(entry.name)) continue;
    const child = rel ? `${rel}/${entry.name}` : entry.name;
    const left = join(a, child);
    const right = join(b, child);
    if (!existsSync(right)) {
      out.onlyUpstream.push(child);
      continue;
    }
    if (entry.isDirectory()) {
      compareTrees(a, b, child, out);
      continue;
    }
    const ls = statSync(left);
    const rs = statSync(right);
    if (ls.size !== rs.size || !readFileSync(left).equals(readFileSync(right))) {
      out.differing.push(child);
    }
  }
}

function main() {
  const root = join(__dirname, "..");
  const vendor = join(root, "vendor", "upstream");

  if (!hasGit()) {
    console.log("check:upstream — git not available, skipping (this is a CI-only check)");
    return;
  }

  const tmp = mkdtempSync(join(tmpdir(), "pi-upstream-check-"));
  try {
    console.log(`check:upstream — fetching ${REPO} @ ${TAG}`);
    git(["clone", "--depth", "1", "--branch", TAG, "--filter=blob:none", "--sparse", REPO, tmp]);
    git(["sparse-checkout", "set", ...SPARSE_PATHS], tmp);

    const out = { onlyUpstream: [], missing: [], differing: [] };
    for (const p of SPARSE_PATHS) compareTrees(tmp, vendor, p, out);

    const unexpected = [...out.onlyUpstream, ...out.differing].filter((p) => !ALLOWED.includes(p));

    if (out.missing.length) {
      console.log(`check:upstream — vendored paths missing vs upstream: ${out.missing.join(", ")}`);
    }
    if (unexpected.length === 0) {
      const tolerated = [...out.onlyUpstream, ...out.differing].length;
      console.log(
        `check:upstream — OK: vendor/upstream matches ${TAG} byte-for-byte` +
          (tolerated ? ` (${tolerated} documented local difference(s) tolerated)` : ""),
      );
      return;
    }

    console.error("check:upstream — FAILED: vendored files differ from the pinned tag");
    for (const p of unexpected) console.error(`  differs or is upstream-only: ${p}`);
    console.error(
      "\nEither restore the file with:\n" +
        `  git -C ${tmp} show HEAD:${unexpected[0]} > "${join(vendor, unexpected[0])}"\n` +
        "or, if the change is intentional, document it in docs/UPSTREAM.md and add it to ALLOWED here.",
    );
    process.exitCode = 1;
  } finally {
    try {
      rmSync(tmp, { recursive: true, force: true });
    } catch {
      // temp dir cleanup is best-effort
    }
  }
}

main();
